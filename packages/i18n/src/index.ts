export const translations = { ar, en } as const;

export type TranslationKey = keyof typeof ar;

export function t(key: TranslationKey, locale: Locale = 'ar'): string {
  return translations[locale][key] ?? translations.ar[key];
}

export function messagesFor(locale: Locale): Record<TranslationKey, string> {
  return { ...translations[locale] };
}

export function isRtl(locale: Locale): boolean {
  return locale === 'ar';
}

export function dirFor(locale: Locale): 'rtl' | 'ltr' {
  return isRtl(locale) ? 'rtl' : 'ltr';
}
